inline std::vector<sgb::ProviderResult> search(
    const std::string& indexerId,
    const std::string& query)
{
    std::vector<sgb::ProviderResult> results;

    const std::string clean = sgb_api::trim(query);

    if (clean.empty())
        return results;

    const Config config = loadConfig();

    const std::string url =
        config.url +
        "/api/v2.0/indexers/" +
        sgb_api::urlEncode(indexerId) +
        "/results/torznab/api?apikey=" +
        sgb_api::urlEncode(config.apiKey) +
        "&t=search&q=" +
        sgb_api::urlEncode(clean);

    const std::string xml =
        sgb_api::httpGet(
            url,
            "application/rss+xml, application/xml, text/xml, */*");

    static const std::regex itemRe(
        R"(<item\b[\s\S]*?</item>)",
        std::regex::icase);

    std::unordered_set<std::string> seen;

    for (
        auto it =
            std::sregex_iterator(
                xml.begin(),
                xml.end(),
                itemRe);
        it != std::sregex_iterator();
        ++it
    ) {
        const std::string item = it->str();

        const std::string title =
            sgb_api::trim(
                sgb_api::tagValue(item, "title"));

        std::string magnet =
            sgb_api::trim(
                sgb_api::torznabAttr(
                    item,
                    "magneturl"));

        if (magnet.empty()) {
            magnet =
                sgb_api::trim(
                    sgb_api::torznabAttr(
                        item,
                        "magnet"));
        }

        if (magnet.empty()) {
            const std::string link =
                sgb_api::trim(
                    sgb_api::tagValue(
                        item,
                        "link"));

            if (link.rfind("magnet:", 0) == 0)
                magnet = link;
        }

        if (magnet.empty()) {
            const std::string guid =
                sgb_api::trim(
                    sgb_api::tagValue(
                        item,
                        "guid"));

            if (guid.rfind("magnet:", 0) == 0)
                magnet = guid;
        }

        std::string hash =
            sgb_api::lowerAscii(
                sgb_api::trim(
                    sgb_api::torznabAttr(
                        item,
                        "infohash")));

        if (hash.empty() && !magnet.empty())
            hash = sgb_api::hashFromMagnet(magnet);

        if (
            title.empty() ||
            !sgb_api::validInfoHash(hash)
        ) {
            continue;
        }

        if (!seen.insert(hash).second)
            continue;

        if (magnet.empty()) {
            magnet =
                sgb_api::magnetFromHash(
                    hash,
                    title);
        }

        sgb::ProviderResult row;
        row.title = title;
        row.magnet = magnet;
        row.infoHash = hash;
        results.push_back(std::move(row));
    }

    return results;
}

