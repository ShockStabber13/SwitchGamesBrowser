bool saveScrapeCache(
    const std::string& root,
    const std::string& gameTitle,
    DebridService debridService,
    const std::vector<Release>& releases,
    const std::map<std::string, DebridTorrentStatus>& statuses)
{
    if (!prepareCacheDirectory(root, debridService))
        return false;

    Json rows = Json::array();

    for (const auto& release : releases)
        rows.push_back(releaseToJson(release));

    Json statusJson =
        Json::parse(
            serializeDebridStatusJson(statuses),
            nullptr,
            false);

    if (
        statusJson.is_discarded() ||
        !statusJson.is_object()
    ) {
        statusJson = Json::object();
    }

    Json rootJson{
        {"version", 2},
        {"gameTitle", gameTitle},
        {"debridService", serviceFolder(debridService)},
        {
            "savedAt",
            static_cast<long long>(
                std::time(nullptr))
        },
        {"releases", std::move(rows)},
        {"statuses", std::move(statusJson)}
    };

    const std::string target =
        cachePath(
            root,
            gameTitle,
            debridService);

    const std::string temporary =
        target + ".tmp";

    {
        std::ofstream file(
            temporary,
            std::ios::binary |
            std::ios::trunc);

        if (!file)
            return false;

        const std::string payload =
            rootJson.dump();

        file.write(
            payload.data(),
            static_cast<std::streamsize>(
                payload.size()));

        file.flush();

        if (!file)
            return false;
    }

    std::remove(target.c_str());

    if (
        std::rename(
            temporary.c_str(),
            target.c_str()) != 0
    ) {
        std::remove(
            temporary.c_str());

        return false;
    }

    return true;
}

bool loadScrapeCache(
    const std::string& root,
    const std::string& gameTitle,
    DebridService debridService,
    std::vector<Release>& releases,
    std::map<std::string, DebridTorrentStatus>& statuses,
    std::time_t* savedAt)
{
    Json json;

    if (
        !readCache(
            root,
            gameTitle,
            debridService,
            json)
    ) {
        return false;
    }

    std::vector<Release> loaded;

    for (const auto& item : json["releases"]) {
        Release release;

        if (releaseFromJson(item, release))
            loaded.push_back(
                std::move(release));
    }

    statuses =
        parseDebridStatusJson(
            json["statuses"].dump());

    if (savedAt) {
        *savedAt =
            static_cast<std::time_t>(
                json.value(
                    "savedAt",
                    0LL));
    }

    releases =
        std::move(loaded);

    return true;
}

ScrapeCacheInfo scrapeCacheInfo(
    const std::string& root,
    const std::string& gameTitle,
    DebridService debridService)
{
    ScrapeCacheInfo info;

    Json json;

    if (
        !readCache(
            root,
            gameTitle,
            debridService,
            json)
    ) {
        return info;
    }

    info.available = true;

    info.savedAt =
        static_cast<std::time_t>(
            json.value(
                "savedAt",
                0LL));

    info.releaseCount =
        json["releases"].size();

    return info;
}

std::string scrapeCacheAgeText(
    std::time_t savedAt)
{
    if (savedAt <= 0)
        return "unknown age";

    const std::time_t now =
        std::time(nullptr);

    if (now <= savedAt)
        return "just now";

    const long long seconds =
        static_cast<long long>(
            now - savedAt);

    if (seconds < 60)
        return "just now";

    const long long minutes =
        seconds / 60;

    if (minutes < 60)
        return
            std::to_string(minutes) +
            "m ago";

    const long long hours =
        minutes / 60;

    if (hours < 48)
        return
            std::to_string(hours) +
            "h ago";

    const long long days =
        hours / 24;

    return
        std::to_string(days) +
        "d ago";
}

