uint64_t fnv1a64(const std::string& value)
{
    uint64_t hash = UINT64_C(1469598103934665603);

    for (unsigned char c : value) {
        hash ^= static_cast<uint64_t>(c);
        hash *= UINT64_C(1099511628211);
    }

    return hash;
}

