bool releaseFromJson(
    const Json& item,
    Release& release)
{
    if (!item.is_object())
        return false;

    release.title =
        item.value(
            "title",
            std::string{});

    release.magnet =
        item.value(
            "magnet",
            std::string{});

    release.infoHash =
        item.value(
            "infoHash",
            std::string{});

    release.source =
        item.value(
            "source",
            std::string{});

    return
        !release.title.empty() &&
        (
            !release.infoHash.empty() ||
            !release.magnet.empty()
        );
}

bool readCache(
    const std::string& root,
    const std::string& gameTitle,
    DebridService debridService,
    Json& json)
{
    std::ifstream file(
        cachePath(
            root,
            gameTitle,
            debridService),
        std::ios::binary);

    if (!file)
        return false;

    json =
        Json::parse(
            file,
            nullptr,
            false);

    if (
        json.is_discarded() ||
        !json.is_object()
    ) {
        return false;
    }

    if (json.value("version", 0) != 2)
        return false;

    if (
        json.value(
            "gameTitle",
            std::string{}) !=
        gameTitle
    ) {
        return false;
    }

    if (
        json.value(
            "debridService",
            std::string{}) !=
        serviceFolder(debridService)
    ) {
        return false;
    }

    return
        json.contains("releases") &&
        json["releases"].is_array() &&
        json.contains("statuses") &&
        json["statuses"].is_object();
}

